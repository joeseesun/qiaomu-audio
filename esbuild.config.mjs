import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";
import { builtinModules } from "module";

const prod = process.argv[2] === "production";
// ws is loaded only through the desktop Edge speech dynamic import; keep its Node builtins as node: requires.
const speechWebSocket = {
  name: "desktop-speech-websocket",
  setup(build) {
    build.onResolve({ filter: /^ws$/ }, () => ({ path: path.resolve("node_modules/ws/lib/websocket.js") }));
    build.onLoad({ filter: /node_modules[\\/]ws[\\/].*\.js$/ }, async ({ path: file }) => {
      const source = await fs.promises.readFile(file, "utf8");
      return { contents: source.replace(/require\('(events|https|http|net|tls|crypto|stream|url|buffer|zlib|util)'\)/g, "require('node:$1')"), loader: "js" };
    });
  },
};
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/joeseesun/qiaomu-audio
PROJECT LICENSE — GPL-3.0-only. Copyright (c) 2026 向阳乔木
Edge TTS interoperability: LGPLv3 (licenses/edge-tts-LGPL.txt in the source repository).
Speech-recognition service list and protocols adapted from Qiaomu Clipper (MIT).
${fs.readFileSync("node_modules/ws/LICENSE", "utf8").replaceAll("*/", "* /")}
*/`;

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.js"],
  bundle: true,
  external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtinModules, ...builtinModules.map(m => `node:${m}`)],
  format: "cjs",
  target: "es2022",
  loader: { ".py": "text" },
  plugins: [speechWebSocket],
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
});
if (prod) { await context.rebuild(); process.exit(0); } else await context.watch();
